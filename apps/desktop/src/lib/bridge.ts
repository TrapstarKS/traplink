export function nativeCommand<T>(command: string, args?: Record<string, unknown>): Promise<T> {
  if (!nativeAvailable) return Promise.reject(new Error("This action is available in the TrapLink desktop app."));
  return invoke<T>(command, args);
}

export async function chooseFile(): Promise<string | null> {
  return nativeCommand<string | null>("select_file");
}

export async function chooseDirectory(): Promise<string | null> {
  return nativeCommand<string | null>("select_folder");
}

export async function chooseBackupDestination(name: string): Promise<string | null> {
  return nativeCommand<string | null>("select_backup_destination", { defaultName: `${name.replace(/[^\p{L}\p{N} _-]/gu, "").slice(0, 80) || "traplink-backup"}.json` });
}

